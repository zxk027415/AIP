/**
 * 翻译后端数据中的中文文本
 * 英文模式下查表翻译，中文模式下原样返回
 * 支持模式匹配翻译动态生成的描述
 */
const SORTED_TRANSLATION_ENTRIES = Object.entries(ZH_EN_MAP).sort(
  (a, b) => b[0].length - a[0].length,
);
const CHINESE_CHAR_RE = /[\u4e00-\u9fff]/;

const TD_CACHE_MAX_SIZE = 8000;
const TD_CACHE_ZH = new Map<string, string>();
const TD_CACHE_EN = new Map<string, string>();

function cacheGet(cache: Map<string, string>, key: string): string | undefined {
  return cache.get(key);
}

function cacheSet(cache: Map<string, string>, key: string, value: string): string {
  if (cache.size >= TD_CACHE_MAX_SIZE) {
    // Simple bounded cache strategy: clear when full.
    cache.clear();
  }
  cache.set(key, value);
  return value;
}

const EN_ZH_EXACT_MAP: Record<string, string> = {};
const EN_ZH_LOWER_MAP: Record<string, string> = {};
for (const [zh, en] of Object.entries(ZH_EN_MAP)) {
  if (!en) continue;
  if (!EN_ZH_EXACT_MAP[en]) EN_ZH_EXACT_MAP[en] = zh;
  const lowerEn = en.toLowerCase();
  if (!EN_ZH_LOWER_MAP[lowerEn]) EN_ZH_LOWER_MAP[lowerEn] = zh;
}

export function td(text: string | undefined | null): string {
  if (!text) return '';
  const isZh = (i18n.language || '').toLowerCase().startsWith('zh');
  const cache = isZh ? TD_CACHE_ZH : TD_CACHE_EN;
  const cached = cacheGet(cache, text);
  if (cached !== undefined) return cached;

  if (isZh) {
    // 中文模式下支持英文节点名/描述反向映射回中文
    if (EN_ZH_EXACT_MAP[text]) return cacheSet(cache, text, EN_ZH_EXACT_MAP[text]);
    const lower = text.toLowerCase();
    if (EN_ZH_LOWER_MAP[lower]) return cacheSet(cache, text, EN_ZH_LOWER_MAP[lower]);
    return cacheSet(cache, text, text);
  }
  // Exact match
  if (ZH_EN_MAP[text]) return cacheSet(cache, text, ZH_EN_MAP[text]);
  // Pattern-based translation for auto-generated workflow descriptions
  const scenarioPattern = /^为场景\s+(\S+)\s+生成(?:算法模板|工作流)[：:，,]\s*(.*)$/;
  const scenarioMatch = text.match(scenarioPattern);
  if (scenarioMatch) {
    const scenarioId = scenarioMatch[1];
    let details = scenarioMatch[2];
    // Translate common terms in the details
    details = details
      .replace(/数据接入层/g, 'Data Ingestion')
      .replace(/数据管理层/g, 'Data Management')
      .replace(/数据处理层/g, 'Data Processing')
      .replace(/算法模型层/g, 'Algorithm Model')
      .replace(/评估输出层/g, 'Evaluation Output')
      .replace(/个节点/g, ' nodes')
      .replace(/条连接/g, ' connections')
      .replace(/共/g, 'total')
      .replace(/，/g, ', ')
      .replace(/、/g, ', ');
    return `Generated template for ${scenarioId}: ${details}`;
  }
  // Pattern for "基于 Kaggle..." descriptions
  const kagglePattern = /^基于\s*Kaggle\s*/;
  if (kagglePattern.test(text)) {
    return text.replace(/^基于/, 'Based on')
      .replace(/的完整机器学习流程/, ' full ML pipeline')
      .replace(/使用基础算法库通用函数/, 'using basic algorithm library functions')
      .replace(/目标：/, 'Goal: ')
      .replace(/复现/, 'replicate')
      .replace(/论文精度/, 'paper accuracy');
  }
  // Pattern for PV station datasets with year suffix
  const pvStationYearPattern = /^(?:光伏|PV)电站([A-Z]?)-(\d{4})年数据$/;
  const pvStationMatch = text.match(pvStationYearPattern);
  if (pvStationMatch) {
    const station = pvStationMatch[1] ? ` ${pvStationMatch[1]}` : '';
    const year = pvStationMatch[2];
    return cacheSet(cache, text, `PV Station${station} - ${year} Data`);
  }

  // Pattern-based translation for pipeline execution logs
  const pipelineStartPattern = /^流水线开始执行:\s*(.+?)\s*\(算子数:\s*(\d+)\)$/;
  const pipelineStartMatch = text.match(pipelineStartPattern);
  if (pipelineStartMatch) {
    return cacheSet(cache, text, `Pipeline started: ${td(pipelineStartMatch[1])} (operators: ${pipelineStartMatch[2]})`);
  }

  const pipelineDonePattern = /^✓\s*流水线执行完成[，,]\s*总耗时\s*([0-9.]+s)$/;
  const pipelineDoneMatch = text.match(pipelineDonePattern);
  if (pipelineDoneMatch) {
    return cacheSet(cache, text, `✓ Pipeline completed, total duration ${pipelineDoneMatch[1]}`);
  }

  const nodeStartPattern = /^▶\s*(.+?)\s*开始执行\.\.\.$/;
  const nodeStartMatch = text.match(nodeStartPattern);
  if (nodeStartMatch) {
    return cacheSet(cache, text, `▶ ${td(nodeStartMatch[1])} started...`);
  }

  const nodeDonePattern = /^✓\s*(.+?)\s*完成\s*\(耗时\s*([0-9.]+s)\)$/;
  const nodeDoneMatch = text.match(nodeDonePattern);
  if (nodeDoneMatch) {
    return cacheSet(cache, text, `✓ ${td(nodeDoneMatch[1])} completed (${nodeDoneMatch[2]})`);
  }

  const nodeFailPattern = /^✗\s*(.+?)\s*失败:\s*(.+)$/;
  const nodeFailMatch = text.match(nodeFailPattern);
  if (nodeFailMatch) {
    return cacheSet(cache, text, `✗ ${td(nodeFailMatch[1])} failed: ${td(nodeFailMatch[2])}`);
  }

  const missingFunctionPattern = /^✗\s*(.+?)\s*缺少 functionId[，,]\s*跳过$/;
  const missingFunctionMatch = text.match(missingFunctionPattern);
  if (missingFunctionMatch) {
    return cacheSet(cache, text, `✗ ${td(missingFunctionMatch[1])} missing functionId, skipped`);
  }

  const notRegisteredPattern = /^\s*算子\s+(.+?)\s+未注册[，,]\s*使用旧路由$/;
  const notRegisteredMatch = text.match(notRegisteredPattern);
  if (notRegisteredMatch) {
    return cacheSet(cache, text, `Operator ${notRegisteredMatch[1]} is not registered, using legacy router`);
  }

  const canceledPattern = /^⊘\s*执行已被用户取消$/;
  if (canceledPattern.test(text)) {
    return cacheSet(cache, text, '⊘ Execution canceled by user');
  }

  const nestedNodeLogPattern = /^\s*\[(.+?)\]\s*(.+)$/;
  const nestedNodeLogMatch = text.match(nestedNodeLogPattern);
  if (nestedNodeLogMatch) {
    return cacheSet(cache, text, `  [${td(nestedNodeLogMatch[1])}] ${td(nestedNodeLogMatch[2])}`);
  }

  // XGBoost training logs (mixed/legacy variants)
  const xgbTrainLogPatternZh = /^\[XGBoost forecast\]\s*模型训练完成[，,]\s*(\d+)个特征[，,]\s*开始生成测试集预测\.\.\.$/;
  const xgbTrainLogPatternMixed = /^\[XGBoost forecast\]\s*Model Training完成[，,]\s*(\d+)个特征[，,]\s*Start生成测试集Predict\.\.\.$/;
  const xgbTrainLogMatch = text.match(xgbTrainLogPatternZh) || text.match(xgbTrainLogPatternMixed);
  if (xgbTrainLogMatch) {
    return cacheSet(cache, text, `[XGBoost forecast] Model training completed, ${xgbTrainLogMatch[1]} features, generating test-set predictions...`);
  }

  const xgbPredDonePatternZh = /^\[XGBoost forecast\]\s*预测完成:\s*model_id=([^,，\s]+)[，,]\s*预测(\d+)个点$/;
  const xgbPredDonePatternMixed = /^\[XGBoost forecast\]\s*Predict完成:\s*model_id=([^,，\s]+)[，,]\s*Predict(\d+)个点$/;
  const xgbPredDoneMatch = text.match(xgbPredDonePatternZh) || text.match(xgbPredDonePatternMixed);
  if (xgbPredDoneMatch) {
    return cacheSet(cache, text, `[XGBoost forecast] Prediction completed: model_id=${xgbPredDoneMatch[1]}, points=${xgbPredDoneMatch[2]}`);
  }
  // Fast path: pure non-Chinese text doesn't need greedy dictionary replacement.
  if (!CHINESE_CHAR_RE.test(text)) {
    return cacheSet(cache, text, text);
  }
  // Fallback: greedy phrase replacement for mixed/combined Chinese titles
  let fallback = text;
  for (const [zh, en] of SORTED_TRANSLATION_ENTRIES) {
    if (zh.length < 2) continue;
    if (fallback.includes(zh)) {
      fallback = fallback.split(zh).join(en);
    }
  }
  if (fallback !== text) {
    return cacheSet(
      cache,
      text,
      fallback
      .replace(/（/g, ' (')
      .replace(/）/g, ')')
      .replace(/：/g, ': ')
      .replace(/，/g, ', ')
      .replace(/([a-z])([A-Z])/g, '$1 $2')
      .replace(/\s{2,}/g, ' ')
      .trim(),
    );
  }
  return cacheSet(cache, text, text);
}
